/**
 * Generates the container of a table declared with {@code storage = TableStorage.COLUMNAR}.
 *
 * <p>Rows and indices are kept by a {@link ColumnarEntityList} over the columns generated by {@link
 * TableColumnsGenerator}. For each @Index field, the container has {@code byX(key)}, {@code
 * byXAsMap()} and the deprecated {@code byXMap()}, which creates every row at once.
 */
public class ColumnarTableContainerGenerator {

  private static final String KEY_COLUMN_NAMES = "KEY_COLUMN_NAMES";
  private static final String COLUMN_THRESHOLD = "COLUMN_THRESHOLD";

  private final GtfsFileDescriptor fileDescriptor;
  private final GtfsEntityClasses classNames;
  private final ClassName entityType;
  private final ParameterizedTypeName tableDescriptorType;
  private final ParameterizedTypeName entityListType;
  private final ParameterizedTypeName listType;

  public ColumnarTableContainerGenerator(GtfsFileDescriptor fileDescriptor) {
    this.fileDescriptor = fileDescriptor;
    this.classNames = new GtfsEntityClasses(fileDescriptor);
    this.entityType = classNames.entityImplementationTypeName();
    this.tableDescriptorType =
        ParameterizedTypeName.get(ClassName.get(GtfsTableDescriptor.class), entityType);
    this.entityListType =
        ParameterizedTypeName.get(ClassName.get(ColumnarEntityList.class), entityType);
    this.listType = ParameterizedTypeName.get(ClassName.get(List.class), entityType);
  }

  public JavaFile generateGtfsContainerJavaFile() {
    return JavaFile.builder(TABLE_PACKAGE_NAME, generateGtfsContainerClass()).build();
  }

  /** Name of the system property that sets the column threshold, e.g., for stop_times.txt. */
  private String columnThresholdProperty() {
    String table = StringUtils.removeEnd(fileDescriptor.filename(), ".txt");
    return "gtfsvalidator."
        + CaseFormat.LOWER_UNDERSCORE.to(CaseFormat.LOWER_CAMEL, table)
        + ".columnThreshold";
  }

  public TypeSpec generateGtfsContainerClass() {
    TypeSpec.Builder typeSpec =
        TypeSpec.classBuilder(classNames.tableContainerSimpleName())
            .superclass(
                ParameterizedTypeName.get(
                    ClassName.get(GtfsTableContainer.class), entityType, tableDescriptorType))
            .addAnnotation(Generated.class)
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addJavadoc(
                "Container for $L. Large tables are kept as columns, see {@link $T}.",
                fileDescriptor.filename(),
                ColumnarEntityList.class);

    typeSpec.addField(
        FieldSpec.builder(
                ParameterizedTypeName.get(ImmutableList.class, String.class),
                KEY_COLUMN_NAMES,
                Modifier.PRIVATE,
                Modifier.STATIC,
                Modifier.FINAL)
            .initializer(
                "$T.of($L)",
                ImmutableList.class,
                fileDescriptor.primaryKeys().stream()
                    .map((f) -> CodeBlock.of("$T.$L", entityType, fieldNameField(f.name())))
                    .collect(CodeBlock.joining(", ")))
            .build());
    typeSpec.addField(
        FieldSpec.builder(int.class, COLUMN_THRESHOLD, Modifier.STATIC, Modifier.FINAL)
            .initializer("Integer.getInteger($S, 1_000_000)", columnThresholdProperty())
            .build());
    typeSpec.addField(entityListType, "entities", Modifier.PRIVATE, Modifier.FINAL);

    typeSpec.addMethod(
        MethodSpec.constructorBuilder()
            .addModifiers(Modifier.PRIVATE)
            .addParameter(tableDescriptorType, "descriptor")
            .addParameter(CsvHeader.class, "header")
            .addParameter(entityListType, "entities")
            .addStatement(
                "super(descriptor, $T.PARSABLE_HEADERS_AND_ROWS, header)", TableStatus.class)
            .addStatement("this.entities = entities")
            .build());
    typeSpec.addMethod(
        MethodSpec.constructorBuilder()
            .addModifiers(Modifier.PUBLIC)
            .addParameter(tableDescriptorType, "descriptor")
            .addParameter(TableStatus.class, "tableStatus")
            .addStatement("super(descriptor, tableStatus, $T.EMPTY)", CsvHeader.class)
            .addStatement("this.entities = createEntityList()")
            .addStatement(
                "entities.finish($T.FILENAME, new $T())", entityType, NoticeContainer.class)
            .build());
    typeSpec.addMethod(
        MethodSpec.methodBuilder("createEntityList")
            .addModifiers(Modifier.STATIC)
            .returns(entityListType)
            .addStatement("return createEntityList($L)", COLUMN_THRESHOLD)
            .build());
    typeSpec.addMethod(
        MethodSpec.methodBuilder("createEntityList")
            .addJavadoc(
                "Creates the list the loader adds rows to, kept as columns from the given row.")
            .addModifiers(Modifier.STATIC)
            .addParameter(int.class, "columnThreshold")
            .returns(entityListType)
            .addStatement(
                "return new $T<>(new $T(), columnThreshold)",
                ColumnarEntityList.class,
                classNames.tableColumnsTypeName())
            .build());

    typeSpec.addMethod(
        MethodSpec.methodBuilder("getEntityClass")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Class.class), entityType))
            .addStatement("return $T.class", entityType)
            .build());
    typeSpec.addMethod(
        MethodSpec.methodBuilder("gtfsFilename")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(String.class)
            .addStatement("return $T.FILENAME", entityType)
            .build());
    typeSpec.addMethod(
        MethodSpec.methodBuilder("getEntities")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(listType)
            .addStatement("return entities")
            .build());

    typeSpec.addMethod(generateForHeaderAndEntitiesMethod());
    typeSpec.addMethod(generateForEntitiesMethod());
    typeSpec.addMethod(generateForStatusMethod());

    for (int i = 0; i < fileDescriptor.indices().size(); i++) {
      addIndexMethods(typeSpec, i, fileDescriptor.indices().get(i));
    }

    typeSpec.addMethod(generateByTranslationKeyMethod());
    typeSpec.addMethod(
        MethodSpec.methodBuilder("getKeyColumnNames")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ImmutableList.class, String.class))
            .addStatement("return $L", KEY_COLUMN_NAMES)
            .build());
    return typeSpec.build();
  }

  private MethodSpec generateForHeaderAndEntitiesMethod() {
    TypeName tableContainerType = classNames.tableContainerTypeName();
    return MethodSpec.methodBuilder("forHeaderAndEntities")
        .addJavadoc("Creates a table with given header and entities.")
        .addAnnotation(
            AnnotationSpec.builder(SuppressWarnings.class)
                .addMember("value", "$S", "unchecked")
                .build())
        .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
        .returns(tableContainerType)
        .addParameter(tableDescriptorType, "descriptor")
        .addParameter(CsvHeader.class, "header")
        .addParameter(listType, "entities")
        .addParameter(NoticeContainer.class, "noticeContainer")
        .addStatement("$T list", entityListType)
        .beginControlFlow("if (entities instanceof $T)", ColumnarEntityList.class)
        .addStatement("list = ($T) entities", entityListType)
        .nextControlFlow("else")
        .addStatement("list = createEntityList()")
        .addStatement("list.addAll(entities)")
        .endControlFlow()
        .addStatement("list.finish($T.FILENAME, noticeContainer)", entityType)
        .addStatement("return new $T(descriptor, header, list)", tableContainerType)
        .build();
  }

  private MethodSpec generateForEntitiesMethod() {
    return MethodSpec.methodBuilder("forEntities")
        .addJavadoc(
            "Creates a table with given entities and empty header. This method is intended for"
                + " tests.")
        .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
        .returns(classNames.tableContainerTypeName())
        .addParameter(listType, "entities")
        .addParameter(NoticeContainer.class, "noticeContainer")
        .addStatement(
            "return forHeaderAndEntities(new $T(), $T.EMPTY, entities, noticeContainer)",
            classNames.tableDescriptorTypeName(),
            CsvHeader.class)
        .build();
  }

  private MethodSpec generateForStatusMethod() {
    return MethodSpec.methodBuilder("forStatus")
        .addJavadoc(
            "Creates a table with the given TableStatus. This method is intended for tests.")
        .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
        .returns(classNames.tableContainerTypeName())
        .addParameter(TableStatus.class, "tableStatus")
        .addStatement(
            "return new $T(new $T(), tableStatus)",
            classNames.tableContainerTypeName(),
            classNames.tableDescriptorTypeName())
        .build();
  }

  private void addIndexMethods(TypeSpec.Builder typeSpec, int index, GtfsFieldDescriptor field) {
    TypeName keyType = TypeName.get(field.javaType());
    String methodName = byKeyMethodName(field.name());
    String column = gtfsColumnName(field.name());
    String sortedBy =
        index == fileDescriptor.sequenceIndex()
            ? ", sorted by " + gtfsColumnName(fileDescriptor.sequenceField().get().name())
            : "";
    typeSpec.addMethod(
        MethodSpec.methodBuilder(methodName)
            .addJavadoc("Returns the rows with the given $L$L.", column, sortedBy)
            .addModifiers(Modifier.PUBLIC)
            .addParameter(keyType, "key")
            .returns(listType)
            .addStatement("return entities.byIndex($L, key)", index)
            .build());
    typeSpec.addMethod(
        MethodSpec.methodBuilder(methodName + "AsMap")
            .addJavadoc("Returns the rows of each $L$L, created on access.", column, sortedBy)
            .addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Map.class), keyType.box(), listType))
            .addStatement("return entities.byIndexAsMap($L)", index)
            .build());
    typeSpec.addMethod(
        MethodSpec.methodBuilder(methodName + "Map")
            .addJavadoc(
                "@deprecated creates every row at once, use {@link #$LAsMap()}.", methodName)
            .addAnnotation(Deprecated.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(
                ParameterizedTypeName.get(
                    ClassName.get(ListMultimap.class), keyType.box(), entityType))
            .addStatement("return entities.byIndexMultimap($L)", index)
            .build());
  }

  private MethodSpec generateByTranslationKeyMethod() {
    MethodSpec.Builder method =
        MethodSpec.methodBuilder("byTranslationKey")
            .addAnnotation(Override.class)
            .addModifiers(Modifier.PUBLIC)
            .returns(ParameterizedTypeName.get(ClassName.get(Optional.class), entityType))
            .addParameter(String.class, "recordId")
            .addParameter(String.class, "recordSubId");
    int sequenceIndex = fileDescriptor.sequenceIndex();
    boolean hasRecordId =
        fileDescriptor.primaryKeys().stream()
            .anyMatch((f) -> f.primaryKey().get().translationRecordIdType() == RECORD_ID);
    if (sequenceIndex < 0 || !hasRecordId) {
      return method.addStatement("return Optional.empty()").build();
    }
    return method
        .beginControlFlow("try")
        .addStatement(
            "return entities.byIndexAndSequence($L, $L, $L)",
            sequenceIndex,
            translationKey(fileDescriptor.indices().get(sequenceIndex)),
            translationKey(fileDescriptor.sequenceField().get()))
        .nextControlFlow("catch (NumberFormatException ex)")
        .addStatement("return Optional.empty()")
        .endControlFlow()
        .build();
  }

  /**
   * Value of a primary key field taken from record_id or record_sub_id. As in the generated
   * containers, the default value of the field is used if the record id is empty or unsupported.
   */
  private static CodeBlock translationKey(GtfsFieldDescriptor field) {
    ImmutableMap<TranslationRecordIdType, String> recordIdTypes =
        ImmutableMap.of(RECORD_ID, "recordId", RECORD_SUB_ID, "recordSubId");
    CodeBlock defaultValue = EntityImplementationGenerator.getDefaultValue(field);
    String parameterName = recordIdTypes.get(field.primaryKey().get().translationRecordIdType());
    if (parameterName == null) {
      return defaultValue;
    }
    return CodeBlock.of(
        "$T.isNullOrEmpty($L) ? $L : $L",
        Strings.class,
        parameterName,
        defaultValue,
        TableContainerIndexGenerator.wrapStringAccessorWithTypeConversion(
            field, CodeBlock.of(parameterName)));
  }
}
